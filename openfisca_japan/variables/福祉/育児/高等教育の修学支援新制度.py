class 高等教育の修学支援新制度_減免額算定基準額(Variable):
    value_type = float
    entity = 世帯
    definition_period = DAY
    label = "高等教育の修学支援新制度において減免割合の判定基準となる額"
    reference = "https://laws.e-gov.go.jp/law/501CO0000000049"
    documentation = """
    大学等における修学の支援に関する法律施行令第2条第2項に定める減免額算定基準額。
    市町村民税の課税標準額に所得割の税率を乗じた額から調整控除を差し引いて算出する。

    以下は割り切って実装している。
    - 生計維持者は世帯の親としている。実際には学生本人の所得も合算する。
    - 前年度の12月31日時点で19歳に達している場合の12万円の控除は未実装。
    - 指定都市に住所を有する場合に調整控除を4分の3とする調整は未実装。
    - 市町村民税の所得割が課されない場合に零とする規定は、算出結果が0円を下回る場合に0円とすることで表現している。
    """

    def formula(対象世帯, 対象期間, parameters):
        課税標準額 = 対象世帯("控除後住民税世帯高所得", 対象期間)
        調整控除 = 対象世帯("調整控除", 対象期間)

        二人親である = 対象世帯.nb_persons(世帯.親) == 2
        課税標準額 = 課税標準額 + 二人親である * 対象世帯("世帯主の配偶者の控除後住民税所得", 対象期間)
        調整控除 = 調整控除 + 二人親である * 対象世帯("世帯主の配偶者の調整控除", 対象期間)

        税率 = parameters(対象期間).福祉.育児.高等教育の修学支援新制度.減免額算定基準額の税率

        # 負の数にならないよう、0円未満になった場合は0円に補正
        return np.clip(課税標準額 * 税率 - 調整控除, 0.0, None)


class 高等教育の修学支援新制度_多子世帯である(Variable):
    value_type = bool
    entity = 世帯
    definition_period = DAY
    label = "高等教育の修学支援新制度において多子世帯に該当するか否か"
