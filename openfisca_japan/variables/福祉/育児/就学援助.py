"""
就学援助の実装
"""

from openfisca_core.periods import DAY
from openfisca_core.variables import Variable
from openfisca_japan.entities import 世帯
from openfisca_japan.variables.全般 import 中学生学年, 小学生学年


class 就学援助の対象者がいる(Variable):
    value_type = bool
    entity = 世帯
    definition_period = DAY
    label = "就学援助の対象者がいるか否か"
    reference = "https://www.mext.go.jp/a_menu/shotou/career/05010502/017.htm"
    documentation = """
    学校教育法第19条に基づき、経済的理由によって就学困難と認められる学齢児童生徒の保護者に対して
    市町村が行う援助。対象者は生活保護法第6条第2項に規定する要保護者と、
    市町村教育委員会が要保護者に準ずる程度に困窮していると認める準要保護者の2種類。

    以下は割り切って実装している。
    - 要保護者であるかどうかは「生活保護の算出額が0円より大きい」ことで判定している。
      実際の要保護者の認定は福祉事務所等が行う。
    - 準要保護者（令和6年度 約109万人）は判定していない。準要保護者に対する就学援助は
      平成17年度に国庫補助が廃止され各市町村が単独で実施しており、認定基準を各市町村が
      規定しているため。生活保護の基準額に係数を掛けて認定基準とする市町村が多いが、
      係数も基準額の根拠とする扶助の種類も市町村により異なる。
      したがって、この変数がfalseであっても市町村の基準では対象となる場合がある。
    - 支給される品目（学用品費、修学旅行費、学校給食費等）と金額は市町村により異なるため
      算出していない。なお生活保護を受給している世帯は学用品費等を教育扶助で受給しているため、
      就学援助として支給されるのは修学旅行費や医療費等に限られる
      （要保護児童生徒援助費補助金交付要綱 別記1）。
    """

    def formula(対象世帯, 対象期間, _parameters):
        生活保護受給可能 = 対象世帯("生活保護", 対象期間) > 0

        学年 = 対象世帯.members("学年", 対象期間)
        子である = 対象世帯.has_role(世帯.子)
        小中学生である = (学年 >= 小学生学年.一年生.value) * (学年 <= 中学生学年.三年生.value)

        return 生活保護受給可能 * 対象世帯.any(子である * 小中学生である)
