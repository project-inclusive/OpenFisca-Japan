class 高等教育の修学支援新制度_給付型奨学金_支給割合(Variable):
    value_type = float
    entity = 世帯
    definition_period = DAY
    label = "高等教育の修学支援新制度の給付型奨学金（学資支給金）において世帯の所得等により定まる支給割合"
    reference = "https://laws.e-gov.go.jp/law/416CO0000000002"
    documentation = """
    独立行政法人日本学生支援機構法施行令第8条の2第1項各号に定める支給の割合。
    支給額算定基準額に応じて全額、3分の2、3分の1、4分の1となる。

    支給額算定基準額は同条第4項に定められており、算出方法は授業料等減免の減免額算定基準額
    （大学等における修学の支援に関する法律施行令第2条第2項）と同じであるため、
    「高等教育の修学支援新制度_減免額算定基準額」を用いている。区分の境界の額も同じであるため、
    減免額算定基準額の上限のパラメータを用いている。

    4分の1の支給は多子世帯に限られる。施行令には限定がないが、独立行政法人日本学生支援機構に関する省令
    （https://laws.e-gov.go.jp/law/416M60000080023）が次のように定めているためである。
    - 第23条の2第2項第4号ロ: 支給額算定基準額が51,300円以上の場合は、多子世帯または
      私立の理工農系の学部等（公示対象学部等）に在学する者に限り対象となる
    - 第40条第1項第4号・第2項第2号: 多子世帯でない理工農系の学生は、支給額算定基準額を
      154,500円以上とみなす（＝給付型奨学金は支給されず、授業料等減免のみ受けられる）
    - 第40条第1項第5号・第2項第3号: 多子世帯で資産の合計額が5000万円以上3億円未満の場合も、
      支給額算定基準額を154,500円とみなす（＝給付型奨学金は支給されない）

    授業料等減免と異なり、多子世帯でも所得にかかわらず全額とはならない。

    資産の要件は、省令第23条の2第2項第4号により、多子世帯でなければ5000万円未満が対象となり、
    多子世帯であれば5000万円以上で上記のとおり支給されないため、いずれも5000万円未満で判定している。

    NOTE: 資産には現金や有価証券も含まれるが、本リポジトリの入力項目は預貯金のみのため、
    世帯員の預貯金の合計額で判定している。
    「特に優れた者」という学業成績等の要件は判定していない。
    """

    def formula(対象世帯, 対象期間, parameters):
        支給額算定基準額 = 対象世帯("高等教育の修学支援新制度_減免額算定基準額", 対象期間)
        多子世帯である = 対象世帯("高等教育の修学支援新制度_多子世帯である", 対象期間)
        世帯預貯金 = 対象世帯.sum(対象世帯.members("預貯金", 対象期間))

        制度 = parameters(対象期間).福祉.育児.高等教育の修学支援新制度
        上限 = 制度.減免額算定基準額の上限
        資産要件を満たす = 世帯預貯金 < 制度.給付型奨学金の資産の上限

        # NOTE: 3分の2等の割合は施行令が定める分数のため、丸め誤差を避けるようPythonの除算で表現している
        支給割合 = np.select(
            [支給額算定基準額 < 上限.全額,
             支給額算定基準額 < 上限.三分の二,
             支給額算定基準額 < 上限.三分の一,
             (支給額算定基準額 < 上限.四分の一) * 多子世帯である],
            [1.0,
             2 / 3,
             1 / 3,
             1 / 4],
            0.0)

        return 資産要件を満たす * 支給割合


class 高等教育の修学支援新制度_給付型奨学金の月額_自宅通学(Variable):
    value_type = float
    entity = 人物
    definition_period = DAY
    label = "高等教育の修学支援新制度による世帯員ごとの自宅通学の場合の給付型奨学金の月額"
    reference = "https://laws.e-gov.go.jp/law/416CO0000000002"
    documentation = """
    独立行政法人日本学生支援機構法施行令第8条の2第1項に定める自宅通学の場合の月額。
    3分の2等を乗じた額に百円未満の端数がある場合は百円に切り上げる。
    大学等に在学していない場合は0円。

    NOTE: 生計維持者が生活保護を受けている場合や、児童養護施設に入所していた場合等は、
    自宅通学でも同条第2項のより高い額となる。本リポジトリの「生活保護」は受給できる見込みの額であり
    実際に受給しているかは判別できないため、第2項の額は用いていない。
    第2項の額は自宅外通学の額を超えないため、最小額と最大額の範囲には収まる。
    """

    def formula(対象人物, 対象期間, _parameters):
        履修種別インデックス = 対象人物("高等教育の修学支援新制度_履修種別インデックス", 対象期間)
        運営種別インデックス = 対象人物("高等教育の修学支援新制度_運営種別インデックス", 対象期間)
        支給割合 = 対象人物.世帯("高等教育の修学支援新制度_給付型奨学金_支給割合", 対象期間)

        対象者である = (履修種別インデックス != -1) * (運営種別インデックス != -1)
        月額 = 給付型奨学金の自宅通学の月額表()[履修種別インデックス, 運営種別インデックス]

        # NOTE: 支給割合は単精度浮動小数点数のため、3分の2等を掛けると真の額から数円ずれることがある。
        # 百円未満を切り上げる前に円単位に丸めることで、割り切れる額が1段切り上がってしまうのを防ぐ
        return 対象者である * np.ceil(np.round(月額 * 支給割合) / 100) * 100


