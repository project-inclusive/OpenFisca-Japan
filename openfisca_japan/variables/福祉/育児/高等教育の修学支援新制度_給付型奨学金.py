class 高等教育の修学支援新制度_給付型奨学金_最小(Variable):
    value_type = float
    entity = 世帯
    definition_period = DAY
    label = "高等教育の修学支援新制度による給付型奨学金（学資支給金）の月額の最小額"
    reference = "https://www.jasso.go.jp/shogakukin/about/kyufu/index.html"
    documentation = """
    独立行政法人日本学生支援機構法第17条の2に基づく学資支給金の月額。
    自宅通学か自宅外通学かは入力項目としていないため、月額の低い自宅通学の場合を最小額としている。

    以下は割り切って実装している。
    - 高等専門学校は第4学年・第5学年のみが対象だが、学年を入力できないため判定していない。
    - 夜間の課程および通信による教育は、入力から判別できないため昼間の課程として算出している。
    - 支給を受けられる期間（正規の修業年限）の判定は行っていない。
    - 職業訓練受講給付金等を受けている場合の調整（施行令第8条の2第5項）は行っていない。
    """

    def formula(対象世帯, 対象期間, _parameters):
        return 対象世帯.sum(対象世帯.members("高等教育の修学支援新制度_給付型奨学金の月額_自宅通学", 対象期間))


